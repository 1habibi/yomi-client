/**
 * Конфигурация стратегий кэширования React Query
 *
 * Категории данных:
 * - REALTIME: Данные требующие частого обновления (уведомления, онлайн статусы)
 * - DYNAMIC: Часто изменяемые данные (списки пользователя, статусы)
 * - SEMI_STATIC: Относительно стабильные данные (детали аниме, профили)
 * - STATIC: Редко изменяемые данные (каталоги, рекомендации)
 * - IMMUTABLE: Практически неизменяемые данные (справочники, статистика)
 */

export const QUERY_CACHE_STRATEGIES = {
  /**
   * Для данных в реальном времени (уведомления, онлайн статусы)
   * - Обновляется каждые 30 секунд
   * - Хранится 2 минуты после неиспользования
   */
  REALTIME: {
    staleTime: 30 * 1000, // 30 секунд
    gcTime: 2 * 60 * 1000, // 2 минуты
    refetchInterval: 30 * 1000, // автообновление каждые 30 сек
  },

  /**
   * Для динамичных данных (комментарии, статусы аниме, активность)
   * - Считается актуальным 2 минуты
   * - Хранится 5 минут после неиспользования
   */
  DYNAMIC: {
    staleTime: 2 * 60 * 1000, // 2 минуты
    gcTime: 5 * 60 * 1000, // 5 минут
    retry: 2,
  },

  /**
   * Для обычных данных (списки аниме, пользовательские списки)
   * - Считается актуальным 5 минут
   * - Хранится 15 минут после неиспользования
   */
  NORMAL: {
    staleTime: 5 * 60 * 1000, // 5 минут
    gcTime: 15 * 60 * 1000, // 15 минут
    retry: 2,
  },

  /**
   * Для полустатичных данных (детали аниме, профили пользователей)
   * - Считается актуальным 10 минут
   * - Хранится 30 минут после неиспользования
   */
  SEMI_STATIC: {
    staleTime: 10 * 60 * 1000, // 10 минут
    gcTime: 30 * 60 * 1000, // 30 минут
    retry: 3,
  },

  /**
   * Для статичных данных (популярные аниме, тренды, персональные рекомендации)
   * - Считается актуальным 30 минут
   * - Хранится 60 минут после неиспользования
   */
  STATIC: {
    staleTime: 30 * 60 * 1000, // 30 минут
    gcTime: 60 * 60 * 1000, // 60 минут
    retry: 3,
  },

  /**
   * Для практически неизменяемых данных (похожие аниме, справочники)
   * - Считается актуальным 60 минут
   * - Хранится 2 часа после неиспользования
   */
  IMMUTABLE: {
    staleTime: 60 * 60 * 1000, // 60 минут
    gcTime: 2 * 60 * 60 * 1000, // 2 часа
    retry: 3,
  },
} as const;

/**
 * Конфигурация для мутаций (создание, обновление, удаление)
 */
export const MUTATION_CONFIG = {
  /**
   * Стандартная конфигурация для мутаций
   */
  DEFAULT: {
    retry: 1,
    retryDelay: 500,
  },

  /**
   * Для критичных операций (платежи, важные обновления)
   */
  CRITICAL: {
    retry: 3,
    retryDelay: 1000,
  },

  /**
   * Для некритичных операций (лайки, просмотры)
   */
  NON_CRITICAL: {
    retry: 0,
  },
} as const;

/**
 * Вспомогательная функция для создания кастомной конфигурации
 */
export const createQueryConfig = (
  baseStrategy: keyof typeof QUERY_CACHE_STRATEGIES,
  overrides?: Partial<(typeof QUERY_CACHE_STRATEGIES)[keyof typeof QUERY_CACHE_STRATEGIES]>,
) => ({
  ...QUERY_CACHE_STRATEGIES[baseStrategy],
  ...overrides,
});
